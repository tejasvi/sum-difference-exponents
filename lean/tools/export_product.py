#!/usr/bin/env python3
"""Write EntropyBounds/Glue/Certs/NAME/Product.lean: the product form of the set inequality for a 6.30(a)
certificate, |A -_G B| <= |A|^l10 |B|^l01 |A +_G B|^l11, with the numbers of the certificate's `entropy_ineq`
(read from its Final.lean), proved from `entropy_ineq` by `set_form_prod` (EntropyBounds/Glue/SetFormProd.lean).

Usage: python3 -I tools/export_product.py NAME [NAME ...]
The other generated files of the certificate are not touched.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAT = re.compile(r"pushEntropy Γ p \(fun q => q\) ≤ \((\d+ / \d+) : ℝ\) \* pushEntropy Γ p \(fun q => q\.1\) \+ "
                 r"\((\d+ / \d+) : ℝ\) \* pushEntropy Γ p \(fun q => q\.2\)\s*\+ \((\d+ / \d+) : ℝ\) \* "
                 r"pushEntropy Γ p \(fun q => q\.1 \+ q\.2\)")

TEMPLATE = """import EntropyBounds.Glue.Certs.{name}.Final
import EntropyBounds.Glue.SetFormProd

/-!
# `{cert}`: the product form of the set inequality

`set_ineq_prod`: for finite `A, B ⊆ ℝ` and `G ⊆ A × B`, `|A −_G B| ≤ |A|^λ₁₀ |B|^λ₀₁ |A +_G B|^λ₁₁` with the numbers
`λ` of `entropy_ineq` (from `entropy_ineq` by `set_form_prod`; generated by tools/export_product.py).
-/

open Finset

namespace EntropyBounds.Glue.Certs.{name}

open EntropyBounds.Iid EntropyBounds.Glue SumsDifferences SumsDifferences.NonShannon

theorem set_ineq_prod (A B : Finset ℝ) (G : Finset (ℝ × ℝ)) (hG : G ⊆ A ×ˢ B) :
    (#(G.image fun q => q.1 - q.2) : ℝ)
      ≤ (#A : ℝ) ^ ({l10} : ℝ) * (#B : ℝ) ^ ({l01} : ℝ)
        * (#(G.image fun q => q.1 + q.2) : ℝ) ^ ({l11} : ℝ) :=
  set_form_prod (by norm_num) (by norm_num) (by norm_num) (fun Γ p hinj hp hs => entropy_ineq Γ p hinj hp hs) A B G hG

end EntropyBounds.Glue.Certs.{name}
"""

for name in sys.argv[1:]:
    base = os.path.join(ROOT, "EntropyBounds", "Glue", "Certs", name)
    final = open(os.path.join(base, "Final.lean"), encoding="utf-8").read()
    m = PAT.search(final)
    assert m, name
    cert = re.search(r"# The sum-difference certificate `([^`]+)`", final).group(1)
    out = TEMPLATE.format(name=name, cert=cert, l10=m.group(1), l01=m.group(2), l11=m.group(3))
    open(os.path.join(base, "Product.lean"), "w", encoding="utf-8").write(out)
    print("wrote", os.path.join(base, "Product.lean"), m.group(1), m.group(2), m.group(3))
