class Master:
    def __init__(self, cfg, lat, LA, lab, M, verbose=True):
        self.cfg, self.lat, self.LA, self.M = cfg, lat, LA, M
        nf = lat.nflats
        zero = lab[0]
        uniq = np.unique(lab)
        uniq = uniq[uniq != zero]
        pos = np.full(int(lab.max()) + 1, -1, dtype=np.int64)
        pos[uniq] = np.arange(len(uniq))
        self.colnode = pos[lab]                 # column of each node (-1 for the H = 0 class)
        self.ncls = len(uniq)
        self.gcol = {}
        for i in range(M + 1):
            for j in range(M + 1):
                self.gcol[(i, j)] = self.ncls + len(self.gcol)
        self.Lc = self.ncls + len(self.gcol)
        self.ncol = self.Lc + 1
        self.fixed_rows, self.fixed_lo, self.fixed_hi, self.fixed_tags = [], [], [], []
        self._fixed()
        # active Shannon rows: arrays
        self.sh = dict(kind=np.zeros(0, np.int8), cp=np.zeros(0, np.int8), a=np.zeros(0, np.int64),
                       b=np.zeros(0, np.int64), j=np.zeros(0, np.int64), k=np.zeros(0, np.int64),
                       e1=np.zeros(0, np.int64), e2=np.zeros(0, np.int64))
        self.sig = set()
        self.used = np.zeros(0, dtype=np.int64)
        if verbose:
            print(f"  master: {self.ncls} classes, {len(self.fixed_rows)} fixed rows", flush=True)

    def col(self, cp, f):
        c = self.colnode[cp * self.lat.nflats + f]
        return None if c < 0 else int(c)

    def _add(self, terms, lo, hi, tag):
        d = {}
        for c, a in terms:
            if c is None:
                continue
            d[c] = d.get(c, 0) + a
        d = {c: a for c, a in d.items() if a != 0}
        if not d:
            return
        self.fixed_rows.append(d); self.fixed_lo.append(lo); self.fixed_hi.append(hi); self.fixed_tags.append(tag)

    def _fixed(self):
        cfg, lat, M = self.cfg, self.lat, self.M
        col, add, Lc, gcol = self.col, self._add, self.Lc, self.gcol
        cis = []
        for t, st in enumerate(cfg.steps):
            if st['kind'] == 'fresh' or (st['kind'] == 'copy' and not st['V']):
                new = sorted(st['new'])
                old = list(range(min(new)))
                if not old:
                    continue
                Fo = lat.cl_ids([lat.coord_e[c] for c in old])
                Fn = lat.cl_ids([lat.coord_e[c] for c in new])
                Fa = lat.cl_ids([lat.coord_e[c] for c in old + new])
                cis.append((old, new, Fo, Fn, Fa))
        for cp in (0, 1):
            for (old, new, Fo, Fn, Fa) in cis:
                add([(col(cp, Fn), 1), (col(cp, Fo), 1), (col(cp, Fa), -1)], 0, 0,
                    ('ci', cp, tuple(old), tuple(new), Fn, Fo, Fa))
        Dv = [v for v, t in enumerate(cfg.vtype) if t == 'D']
        dflats = [lat.cl_ids([lat.coord_e[cfg.vatoms[v][0]], lat.coord_e[cfg.vatoms[v][1]]]) for v in Dv]
        for cp in (0, 1):
            for e, labs in enumerate(lat.labels):
                fl = int(lat.nxt[0, e])
                if 'sumXY' in labs:
                    add([(col(cp, fl), 1)], -INF, 1.0, ('bsum', cp, e, fl))
                if 'diffXY' in labs:
                    add([(col(cp, fl), 1), (Lc, -1)], -INF, 0.0, ('bdiff', cp, e, fl))
                if 'atomX' in labs or 'atomY' in labs:
                    add([(col(cp, fl), 1)], -INF, 1.0, ('batom', cp, e, fl))
            for k, Fk in enumerate(dflats):
                add([(col(cp, Fk), 1), (Lc, -1)], 0, 0, ('dpair', cp, k, Fk))
        G = lambda i, j: gcol.get((i, j))
        add([(G(0, 0), 1)], 0, 0, ('g_h00',))
        for (i, j), c in gcol.items():
            add([(c, 1)], 0, INF, ('g_nonneg', i, j))
            if G(i + 1, j) is not None:
                add([(G(i + 1, j), 1), (c, -1)], 0, INF, ('g_monox', i, j))
            if G(i, j + 1) is not None:
                add([(G(i, j + 1), 1), (c, -1)], 0, INF, ('g_monoy', i, j))
            if G(i + 2, j) is not None:
                add([(G(i + 1, j), 2), (c, -1), (G(i + 2, j), -1)], 0, INF, ('g_concx', i, j))
            if G(i, j + 2) is not None:
                add([(G(i, j + 1), 2), (c, -1), (G(i, j + 2), -1)], 0, INF, ('g_concy', i, j))
            if G(i + 1, j) is not None and G(i, j + 1) is not None:
                add([(G(i + 1, j), 1), (G(i, j + 1), 1), (c, -1), (Lc, -1)], 0, INF, ('g_link', i, j))
        add([(G(1, 1), 1)], -INF, 1.0, ('g_h11',))
        for cp in (0, 1):
            for (e, i, j) in grid_forms(cfg, lat):
                gi, gj = (i, j) if cp == 0 else (j, i)
                if (gi, gj) in gcol:
                    fl = int(lat.nxt[0, e])
                    add([(col(cp, fl), 1), (gcol[(gi, gj)], -1)], 0, 0, ('ident', cp, e, i, j, fl))

    def sh_cols(self, kind, cp, a, b, j, k):
        nf = self.lat.nflats
        off = cp.astype(np.int64) * nf
        C = np.stack([self.colnode[off + a], np.where(kind == 1, self.colnode[off + b], -1),
                      np.where(kind == 1, self.colnode[off + j], -1), self.colnode[off + k]], 1)
        V = np.tile(np.array([1, 1, -1, -1], dtype=np.int64), (len(a), 1))
        V[kind == 0, 1] = 0; V[kind == 0, 2] = 0
        return cert4.canon_rows(C, V)

    def add_shannon(self, rows, rd=0):
        kind, cp, a, b, j, k, e1, e2 = rows[:8]
        C, V = self.sh_cols(kind, cp, a, b, j, k)
        nz = (V != 0).any(axis=1)
        keep = []
        for i in np.nonzero(nz)[0]:
            key = (tuple(C[i]), tuple(V[i]))
            if key in self.sig:
                continue
            self.sig.add(key)
            keep.append(i)
        keep = np.array(keep, dtype=np.int64)
        for nm, arr in zip(('kind', 'cp', 'a', 'b', 'j', 'k', 'e1', 'e2'), (kind, cp, a, b, j, k, e1, e2)):
            self.sh[nm] = np.concatenate([self.sh[nm], arr[keep]])
        self.used = np.concatenate([self.used, np.full(len(keep), rd, np.int64)])
        return len(keep)

    def age(self, rd, row_dual, slack, age):
        """drop active Shannon rows that had zero dual and positive slack for `age` rounds (signatures released)"""
        n = len(self.sh['a'])
        useful = (np.abs(row_dual[:n]) > 1e-9) | (slack[:n] < 1e-7)
        self.used[useful] = rd
        drop = self.used < rd - age
        if not drop.any():
            return 0
        C, V = self.sh_cols(self.sh['kind'][drop], self.sh['cp'][drop], self.sh['a'][drop], self.sh['b'][drop],
                            self.sh['j'][drop], self.sh['k'][drop])
        for i in range(len(C)):
            self.sig.discard((tuple(C[i]), tuple(V[i])))
        keep = ~drop
        for nm in self.sh:
            self.sh[nm] = self.sh[nm][keep]
        self.used = self.used[keep]
        return int(drop.sum())

    def lp(self, keep=None):
        sh = self.sh
        if keep is None:
            keep = np.arange(len(sh['a']))
        C, V = self.sh_cols(sh['kind'][keep], sh['cp'][keep], sh['a'][keep], sh['b'][keep], sh['j'][keep], sh['k'][keep])
        m = C >= 0
        rr = np.repeat(np.arange(len(keep)), m.sum(axis=1))
        S = sp.csr_matrix((V[m].astype(float), (rr, C[m])), shape=(len(keep), self.ncol))
        ri, rj, rv = [], [], []
        for r, d in enumerate(self.fixed_rows):
            for c, a in d.items():
                ri.append(r); rj.append(c); rv.append(a)
        Fm = sp.csr_matrix((rv, (ri, rj)), shape=(len(self.fixed_rows), self.ncol))
        A = sp.vstack([S, Fm]).tocsr()
        lo = np.concatenate([np.zeros(len(keep)), np.array(self.fixed_lo)])
        hi = np.concatenate([np.full(len(keep), INF), np.array(self.fixed_hi)])
        tags = ShTags(sh, keep, self.fixed_tags)
        return dict(A=A, lo=lo, hi=hi, ncol=self.ncol, obj_col=self.Lc, tags=tags)

    def node_values(self, xcolv):
        """value per node (0 for the H = 0 class) from the column vector."""
        v = np.zeros(len(self.colnode))
        m = self.colnode >= 0
        v[m] = xcolv[self.colnode[m]]
        return v


class ShTags:
    def __init__(self, sh, keep, other):
        self.sh, self.keep, self.other = sh, keep, other
        self.n = len(keep)

    def __len__(self):
        return self.n + len(self.other)

    def __getitem__(self, i):
        if i < self.n:
            q = self.keep[i]
            s = self.sh
            if s['kind'][q] == 0:
                return ('mono', int(s['cp'][q]), int(s['a'][q]), int(s['k'][q]), int(s['e1'][q]))
            return ('sub', int(s['cp'][q]), int(s['a'][q]), int(s['b'][q]), int(s['j'][q]), int(s['k'][q]),
                    int(s['e1'][q]), int(s['e2'][q]))
        return self.other[i - self.n]


# ----------------------------------------------------------------------------------------------- certificate

def certificate(cfg, lat, master, L, yex, edges, M):
    """Explicit check3 rows from the exact dual of the master; tree flows over joint classes."""
    nf = lat.nflats

    def form(e):
        return [str(x) for x in lat.amb[e]]

    def gens(f):
        return [form(e) for e in lat.gens_of(f)]
    out = []
    lam = Fraction(0)
    imb = {}            # node -> coefficient of H(node) in sum mult * R

    def acc(cp, f, c):
        if f != 0 and c != 0:
            node = cp * nf + f
            imb[node] = imb.get(node, 0) + c
    for r, v in sorted(yex.items()):
        t = L['tags'][r]
        lo, hi = L['lo'][r], L['hi'][r]
        ineq_ge = np.isinf(hi) and not np.isinf(lo)
        mult = -v if ineq_ge else v
        if np.isinf(lo) and not np.isinf(hi):
            lam += v * Fraction(hi)
        kind = t[0]
        if kind == 'mono':
            _, cp, a, k, e1 = t
            acc(cp, a, mult); acc(cp, k, -mult)
            out.append(dict(type='mono', copy=cp, K=gens(k), i=form(e1), mult=str(mult)))
        elif kind == 'sub':
            _, cp, a, b, j, k, e1, e2 = t
            acc(cp, a, mult); acc(cp, b, mult); acc(cp, j, -mult); acc(cp, k, -mult)
            out.append(dict(type='sub', copy=cp, K=gens(k), i=form(e1), j=form(e2), mult=str(mult)))
        elif kind == 'ci':
            _, cp, old, new, Fn, Fo, Fa = t
            acc(cp, Fa, mult); acc(cp, Fo, -mult); acc(cp, Fn, -mult)
            out.append(dict(type='ci', copy=cp, old=list(old), new=list(new), mult=str(mult)))
        elif kind in ('bsum', 'batom', 'bdiff'):
            _, cp, e, fl = t
            acc(cp, fl, -mult)
            out.append(dict(type=kind, copy=cp, f=form(e), mult=str(mult)))
        elif kind == 'dpair':
            _, cp, k, Fk = t
            acc(cp, Fk, -mult)
            out.append(dict(type='dpair', copy=cp, vertex=k, mult=str(mult)))
        elif kind.startswith('g_'):
            out.append(dict(type=kind, ij=list(t[1:]), mult=str(mult)))
        elif kind == 'ident':
            _, cp, e, i, j, fl = t
            acc(cp, fl, -mult)
            fe = form(e)
            if all(Fraction(x) <= 0 for x in fe):
                fe = [str(-Fraction(x)) for x in fe]
            out.append(dict(type='ident', copy=cp, f=fe, ij=[i, j], mult=str(mult)))
        else:
            raise ValueError(kind)
    # adjacency of the node graph: edge rows R = H(dst node) - H(src node) (src gives the generators)
    adj = {}
    for kind, payload, src, dst in edges:
        for s_, d_ in zip(src.tolist(), dst.tolist()):
            if kind == 'xshare':
                pairs = [(nf + s_, d_)]
            else:
                pairs = [(s_, d_), (nf + s_, nf + d_)]
            for (u, w) in pairs:
                adj.setdefault(u, []).append((w, u, w, kind, payload))
                adj.setdefault(w, []).append((u, u, w, kind, payload))
    nmerge = 0
    done = set()
    for start in list(imb.keys()):
        if start in done or imb.get(start, 0) == 0:
            continue
        order, parent = [start], {start: None}
        q = 0
        while q < len(order):
            u = order[q]; q += 1
            for (w, a, b, kind, payload) in adj.get(u, []):
                if w not in parent:
                    parent[w] = (u, a, b, kind, payload)
                    order.append(w)
        done |= set(order)
        for u in reversed(order[1:]):
            c = imb.get(u, 0)
            if c == 0:
                continue
            p, a, b, kind, payload = parent[u]
            # row R = H(b) - H(a) with multiplier m: coef(b) += m, coef(a) -= m
            m = -c if u == b else c
            imb[u] = 0
            imb[p] = imb.get(p, 0) + c
            cpa, fa = divmod(a, nf)
            if kind == 'xshare':
                out.append(dict(type='xshare', G=gens(fa), map=[[x, y] for x, y in payload], mult=str(m)))
            else:
                out.append(dict(type=kind, copy=cpa, G=gens(fa), perm=[[x, y] for x, y in payload], mult=str(m)))
            nmerge += 1
        root = order[0]
        if imb.get(root, 0) != 0:
            raise RuntimeError(f"class imbalance does not vanish: {imb[root]}")
    verts, _ = cert4.cert_vertices(cfg)
    J = dict(problem="two-set exponent: log|X-Y| <= lambda log|X+Y| for finite X, Y in Z",
             config=dict(coords=cfg.N, vertices=verts, note="mutually independent vertices in this order; D = copy of "
                         "(X1,Y1) ~ Gamma, W = variable with law mu^{*i}*nu^{*j}; copy 0 = Gamma, copy 1 = reflected pair "
                         "(-Y,-X) with Gamma' (grid transposed)"),
             grid_depth=M, rows=out, claimed_lambda=f"{lam.numerator}/{lam.denominator}")
    return J, lam, nmerge


# ----------------------------------------------------------------------------------------------- driver

def main():
    job = json.loads(sys.argv[1])
    prefix = sys.argv[2]
    rounds = int(sys.argv[3]) if len(sys.argv) > 3 else 60
    ADD = int(os.environ.get('ADD', 300000))
    ADDFRAC = float(os.environ.get('ADDFRAC', 0.2))
    ADDMAX = int(os.environ.get('ADDMAX', 2000000))
    VTOL = float(os.environ.get('VTOL', 1e-7))
    STALL = int(os.environ.get('STALL', 2))
    AGE = int(os.environ.get('AGE', 0))
    FOCUS = sum(1 << int(c) for c in os.environ.get('FOCUS', '').split(',') if c != '')   # coordinates
    t0 = time.time()
    cfg, ex, autos = build(job)
    lat = Lattice2(cfg, extra=ex, verbose=True, max_flats=job.get('max_flats', 10 ** 7))
    LA = lattice_arrays(lat)
    lab, edges = joint_classes(cfg, lat, LA, autos, pmerge=job.get('pmerge', 0), xshare=job.get('xshare', False))
    M = job.get('M', 12)
    master = Master(cfg, lat, LA, lab, M)
    needf = None
    if FOCUS:
        needf = (LA['supp'] & FOCUS) != 0
    if os.environ.get('FOCUSFORMS'):
        # flats containing any of the given forms (names x0,y0,x1,y1,... then w,v,u,t)
        import re
        names = []
        for k in range(job.get('nD', 2)):
            names += [f'x{k}', f'y{k}']
        names += ['w', 'v', 'u', 't'][:len(job.get('W', []))]
        fe = []
        for sform in os.environ['FOCUSFORMS'].split(','):
            d = [Fraction(0)] * cfg.N
            for sign, var in re.findall(r'([+-]?)([a-z][0-9]*)', sform):
                d[names.index(var)] += -1 if sign == '-' else 1
            e = lat.form_e(d)
            if e is not None:
                fe.append(e)
        fm_ = sum(1 << e for e in fe)
        nf2 = np.array([(mk & fm_) != 0 for mk in lat.masks], dtype=bool)
        needf = nf2 if needf is None else (needf | nf2)
        print(f"  focus forms {len(fe)}: {int(nf2.sum())} flats", flush=True)
    CL = cover_lists(lat)
    print(f"  covers: {len(CL[1])} ({time.time() - t0:.1f}s)", flush=True)
    if os.environ.get('INIT_FROM'):
        descs = pickle.load(open(os.environ['INIT_FROM'], 'rb'))
        NN = len(lat.amb[0])
        pad = lambda g: [Fraction(x) for x in g] + [Fraction(0)] * (NN - len(g))
        rows = [[] for _ in range(8)]
        for kind, cp, Kg, addf in descs:
            if any(len(g) > NN for g in Kg + addf):
                continue
            es = [lat.form_e(pad(g)) for g in Kg]
            ad = [lat.form_e(pad(g)) for g in addf]
            if any(e is None for e in es + ad):
                continue
            k = lat.cl_ids(es) if es else 0
            a = int(lat.nxt[k, ad[0]])
            if kind == 'mono':
                vals = (0, cp, a, 0, 0, k, ad[0], 0)
            else:
                b = int(lat.nxt[k, ad[1]])
                j = lat.cl_ids(es + ad)
                vals = (1, cp, a, b, j, k, ad[0], ad[1])
            for lst, v in zip(rows, vals):
                lst.append(v)
        if rows[0]:
            arr = [np.array(rows[0], np.int8), np.array(rows[1], np.int8)] + [np.array(r, np.int64) for r in rows[2:]]
            n = master.add_shannon(arr, 10 ** 9)          # warm-start rows are never aged out
            print(f"  warm start: {n} rows from {len(descs)} descriptors", flush=True)
    SAVE = int(os.environ.get('SAVE', 5))

    def save_active():
        fm = lambda e: tuple(str(x) for x in lat.amb[e])
        sh = master.sh
        descs = []
        for q in range(len(sh['a'])):
            k = int(sh['k'][q])
            Kg = tuple(fm(g) for g in lat.gens_of(k))
            if sh['kind'][q] == 0:
                descs.append(('mono', int(sh['cp'][q]), Kg, (fm(int(sh['e1'][q])),)))
            else:
                descs.append(('sub', int(sh['cp'][q]), Kg, (fm(int(sh['e1'][q])), fm(int(sh['e2'][q])))))
        pickle.dump(descs, open(prefix + '_active.pkl.tmp', 'wb'))
        os.replace(prefix + '_active.pkl.tmp', prefix + '_active.pkl')
    hist = []
    for rd in range(rounds):
        if os.path.exists(prefix + '.stop'):
            print("stop file found; certifying", flush=True)
            break
        L = master.lp()
        S = solve_lp(L, opts=IPM)
        x = S['col_value']
        xn = master.node_values(x)
        nsh = len(master.sh['a'])
        res = None
        if needf is not None:
            res = oracle(lat, CL, xn, ADDMAX, VTOL, needf=needf)
            if res is not None:
                print(f"   focus rows {len(res[0])}", flush=True)
        if res is None:
            res = oracle(lat, CL, xn, ADDMAX, VTOL)
        nviol = 0 if res is None else len(res[0])
        print(f"round {rd}: value {S['value']:.10f} {S['status']} active {nsh} violated(top) {nviol} "
              f"({time.time() - t0:.1f}s)", flush=True)
        hist.append(S['value'])
        if res is None:
            break
        if AGE > 0:
            slack = L['A'][:nsh] @ x
            nd = master.age(rd, S['row_dual'], slack, AGE)
            if nd:
                print(f"   aged out {nd} rows", flush=True)
        nadd = max(ADD, min(int(ADDFRAC * nviol), ADDMAX))
        added = master.add_shannon([r[:nadd] for r in res], rd)
        if SAVE and rd % SAVE == SAVE - 1:
            save_active()
        if added == 0:
            break
        if len(hist) > STALL and max(hist[-STALL - 1:]) - min(hist[-STALL - 1:]) < 1e-9 and nviol < 2000:
            print("stalled; certifying", flush=True)
            break
    save_active()
    print("certifying ...", flush=True)
    L = master.lp()
    S = solve_lp(L, opts=IPMX)
    print(f"final master {L['A'].shape}: value {S['value']:.12f} {S['status']}", flush=True)
    for tol in (1e-9, 1e-8, 1e-10, 1e-7):
        try:
            yex = cert4.exact_dual(L, S['row_dual'], tol)
        except RuntimeError as e:
            print('tol', tol, e, flush=True)
            continue
        bad = [rr for rr, v in yex.items() if (L['lo'][rr] != L['hi'][rr]) and
               ((np.isinf(L['hi'][rr]) and v > 0) or (np.isinf(L['lo'][rr]) and v < 0))]
        if bad:
            print('tol', tol, 'bad signs', len(bad), flush=True)
            continue
        J, lam, nm = certificate(cfg, lat, master, L, yex, edges, M)
        json.dump(J, open(prefix + '.json', 'w'))
        print(f"certified lambda = {lam} = {float(lam):.12f} -> {prefix}.json ({len(J['rows'])} rows)", flush=True)
        break


if __name__ == '__main__':
    main()
