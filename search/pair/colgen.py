def cover_lists(lat):
    """CSR of covers: for flat K, distinct nxt[K, e] != K with a representative ground form e."""
    nf, m = lat.nxt.shape
    ptr = np.zeros(nf + 1, dtype=np.int64)
    covs, reps = [], []
    for k in range(nf):
        row = lat.nxt[k]
        u, first = np.unique(row, return_index=True)
        sel = u != k
        covs.append(u[sel]); reps.append(first[sel])
        ptr[k + 1] = ptr[k] + int(sel.sum())
    return ptr, np.concatenate(covs), np.concatenate(reps)


def oracle(lat, CL, xcol, kmax, vtol, ks=None, needf=None):
    """Most violated Shannon rows for column values xcol (array over nodes: value of the node's class; 0 for the
    empty flat).  Returns arrays (kind, cp, a, b, j, k, e1, e2, viol) of at most kmax rows (both copies)."""
    ptr, cov, rep = CL
    nf = lat.nflats
    out = []
    cnt = np.diff(ptr)
    if ks is None:
        ks = np.arange(nf)
    for cp in (0, 1):
        xv = xcol[cp * nf:(cp + 1) * nf]
        # monotonicity
        kk = np.repeat(np.arange(nf), cnt)
        vm = xv[cov] - xv[kk]
        badm = vm < -vtol
        if needf is not None:
            badm &= needf[cov]
        bad = np.nonzero(badm)[0]
        if len(bad):
            out.append((np.zeros(len(bad), np.int8), np.full(len(bad), cp, np.int8), cov[bad], np.zeros(len(bad), np.int64),
                        np.zeros(len(bad), np.int64), kk[bad], rep[bad], np.zeros(len(bad), np.int64), vm[bad]))
        # elemental submodularity, grouped by number of covers
        for c in np.unique(cnt[ks]):
            if c < 2:
                continue
            K = ks[cnt[ks] == c]
            ii, jj = np.triu_indices(int(c), 1)
            step = max(1, int(2e7 // (len(ii) + 1)))
            for s0 in range(0, len(K), step):
                Kc = K[s0:s0 + step]
                base = ptr[Kc]
                A = cov[base[:, None] + ii[None, :]]
                B = cov[base[:, None] + jj[None, :]]
                eB = rep[base[:, None] + jj[None, :]]
                eA = rep[base[:, None] + ii[None, :]]
                J = lat.nxt[A, eB]
                ok = (J != A) & (J != B)
                v = xv[A] + xv[B] - xv[J] - xv[Kc][:, None]
                sel = ok & (v < -vtol)
                if needf is not None:
                    sel &= needf[J]
                if sel.any():
                    r, q = np.nonzero(sel)
                    out.append((np.ones(len(r), np.int8), np.full(len(r), cp, np.int8), A[r, q], B[r, q], J[r, q],
                                Kc[r], eA[r, q], eB[r, q], v[r, q]))
    if not out:
        return None
    arrs = [np.concatenate([o[i] for o in out]) for i in range(9)]
    order = np.argsort(arrs[8])[:kmax]
    return [a[order] for a in arrs]


