def lattice_arrays(lat):
    """rank, parent flat, parent ground form, support bitmask per flat (supp(cl G) = union of generator supports)."""
    nf = lat.nflats
    rank = np.array(lat.rank, dtype=np.int64)
    pp = np.array([p for p, e in lat.par], dtype=np.int64)
    pe = np.array([e for p, e in lat.par], dtype=np.int64)
    supp_e = np.array([sum(1 << c for c, x in enumerate(lat.amb[e]) if x != 0) for e in range(lat.m)], dtype=np.int64)
    supp = np.zeros(nf, dtype=np.int64)
    levels = [np.nonzero(rank == r)[0] for r in range(int(rank.max()) + 1)]
    for r in range(1, len(levels)):
        idx = levels[r]
        supp[idx] = supp[pp[idx]] | supp_e[pe[idx]]
    return dict(rank=rank, pp=pp, pe=pe, supp=supp, supp_e=supp_e, levels=levels)


def emap_of(lat, fmap):
    """ground form id of fmap(form) for every ground form (-1 if fmap gives None or a non-ground form)."""
    out = np.full(lat.m, -1, dtype=np.int64)
    for e in range(lat.m):
        g = fmap(lat.amb[e])
        if g is None or not any(x != 0 for x in g):
            continue
        e2 = lat.form_e(g)
        if e2 is not None:
            out[e] = e2
    return out


def images(lat, LA, emap, allow=None):
    """image flat of every flat generated by mappable ground forms (those with emap >= 0) under a coordinate map
    acting on ground forms by emap; closure commutes with the map, so img(cl(P + e)) = nxt[img(P), emap(e)].
    Forward propagation by rank from the empty flat; -1 for flats not generated by mappable forms.
    allow: optional boolean mask of flats to propagate through (a flat outside it gets no image)."""
    img = np.full(lat.nflats, -1, dtype=np.int64)
    img[0] = 0
    E = np.nonzero(emap >= 0)[0]
    if len(E) == 0:
        return img
    EI = emap[E]
    for r in range(len(LA['levels'])):
        P = LA['levels'][r]
        P = P[img[P] >= 0]
        if len(P) == 0:
            continue
        step = max(1, int(2e7 // len(E)))
        for s0 in range(0, len(P), step):
            Pc = P[s0:s0 + step]
            F = lat.nxt[Pc[:, None], E[None, :]].ravel()
            I = lat.nxt[img[Pc][:, None], EI[None, :]].ravel()
            sel = (F != np.repeat(Pc, len(E))) & (img[F] < 0)
            if allow is not None:
                sel &= allow[F]
            F, I = F[sel], I[sel]
            if len(F):
                u, first = np.unique(F, return_index=True)
                img[u] = I[first]
    return img


def perm_map(perm, sign=1):
    """form map for a coordinate map c -> perm[c] (dict, identity elsewhere) with an overall sign."""
    def f(a):
        g = [0 * x for x in a]
        for c, x in enumerate(a):
            if x != 0:
                g[perm.get(c, c)] += sign * x
        return g
    return f


