def joint_classes(cfg, lat, LA, autos, pmerge=0, xshare=False, verbose=True):
    """Union of nodes (cp, f), node id cp * nflats + f, under automorphisms, pmerge and xshare.
    Returns (labels per node, edges list of (u, v, kind, payload)) where payload gives the row data."""
    nf = lat.nflats
    t0 = time.time()
    eu, ev, kinds = [], [], []
    edges = []          # (kind, cp_or_None, perm_items, flat array src, flat array img) blocks
    # automorphisms (both copies)
    for perm in autos:
        img = images(lat, LA, emap_of(lat, perm_map(perm)))
        src = np.nonzero((img >= 0) & (img != np.arange(nf)))[0]
        edges.append(('merge', tuple(sorted(perm.items())), src, img[src]))
    nmerge = sum(len(b[2]) for b in edges)
    # pmerge transpositions (a b): equal marginal laws, different vertices; valid on F iff the touched part of a's
    # vertex is within {a} and that of b's vertex within {b}, and F touches a or b
    Dv = [tuple(cfg.vatoms[v]) for v in cfg.indepD]
    Wv = [(cfg.vatoms[w][0], tuple(cfg.Wpar[w])) for w in sorted(cfg.Wpar)]
    vmask, law = {}, {}
    for (x, y) in Dv:
        vmask[x] = vmask[y] = (1 << x) | (1 << y)
        law[x], law[y] = (1, 0), (0, 1)
    for (w, ij) in Wv:
        vmask[w] = 1 << w
        law[w] = ij
    assert all(t in ('D', 'W') for t in cfg.vtype), "colgen: D and W vertices only"
    supp = LA['supp']
    if pmerge:
        coords = sorted(vmask)
        for a, b in itertools.combinations(coords, 2):
            if law[a] != law[b] or vmask[a] == vmask[b]:
                continue
            if pmerge == 1:
                pass     # moves to untouched targets only are included in the exchange rule below when b untouched
            ra = vmask[a] & ~(1 << a)
            rb = vmask[b] & ~(1 << b)
            ok = ((supp & ra) == 0) & ((supp & rb) == 0) & ((supp & ((1 << a) | (1 << b))) != 0)
            if pmerge == 1:
                # single moves: exactly one of a, b touched
                ok &= ((supp >> a) & 1) != ((supp >> b) & 1)
            img = images(lat, LA, emap_of(lat, perm_map({a: b, b: a})))
            src = np.nonzero(ok & (img >= 0) & (img != np.arange(nf)))[0]
            edges.append(('pmerge', ((a, b), (b, a)), src, img[src]))
    npm = sum(len(b[2]) for b in edges) - nmerge
    nxs = 0
    if xshare:
        # per touched pattern (per vertex: none / x / y / pair / W) enumerate the valid negating maps once
        pattern = np.zeros(nf, dtype=np.int64)
        for k, (x, y) in enumerate(Dv):
            px = (supp >> x) & 1
            py = (supp >> y) & 1
            pattern = pattern * 4 + (px + 2 * py)
        for (w, ij) in Wv:
            pattern = pattern * 2 + ((supp >> w) & 1)
        for pat in np.unique(pattern):
            sel = np.nonzero(pattern == pat)[0]
            if pat == 0:
                continue
            # decode
            p = int(pat)
            wt = []
            for (w, ij) in reversed(Wv):
                wt.append((w, ij, p & 1)); p >>= 1
            wt = wt[::-1]
            dt = []
            for (x, y) in reversed(Dv):
                dt.append((x, y, p & 3)); p >>= 2
            dt = dt[::-1]
            parts = []
            for k, (x, y, s) in enumerate(dt):
                if s == 3:
                    parts.append(('P', k))
                elif s == 1:
                    parts.append(('X', x))
                elif s == 2:
                    parts.append(('Y', y))
            for (w, ij, s) in wt:
                if s:
                    parts.append(('X', w) if ij == (1, 0) else ('Y', w) if ij == (0, 1) else ('W', w, ij))

            def opts(pt):
                if pt[0] == 'P':
                    return [('D', m) for m in range(len(Dv))]
                if pt[0] == 'X':
                    return [('y', m) for m in range(len(Dv))] + [('w', w) for (w, ij) in Wv if ij == (0, 1)]
                if pt[0] == 'Y':
                    return [('x', m) for m in range(len(Dv))] + [('w', w) for (w, ij) in Wv if ij == (1, 0)]
                return [('w', w) for (w, ij) in Wv if ij == (pt[2][1], pt[2][0])]
            for choice in itertools.product(*[opts(pt) for pt in parts]):
                used = [('D', c[1]) if c[0] in ('D', 'x', 'y') else ('W', c[1]) for c in choice]
                if len(set(used)) != len(used):
                    continue
                cmap = {}
                for pt, c in zip(parts, choice):
                    if pt[0] == 'P':
                        x, y = Dv[pt[1]]; xm, ym = Dv[c[1]]
                        cmap[x] = ym; cmap[y] = xm
                    else:
                        tgt = Dv[c[1]][1] if c[0] == 'y' else Dv[c[1]][0] if c[0] == 'x' else c[1]
                        cmap[pt[1]] = tgt

                def fm(a, cmap=cmap):
                    if any(x != 0 and c not in cmap for c, x in enumerate(a)):
                        return None
                    g = [0 * x for x in a]
                    for c, x in enumerate(a):
                        if x != 0:
                            g[cmap[c]] -= x
                    return g
                img = images(lat, LA, emap_of(lat, fm))
                ok = sel[img[sel] >= 0]
                if len(ok):
                    edges.append(('xshare', tuple(sorted(cmap.items())), ok, img[ok]))
                    nxs += len(ok)
    # union-find via connected components on the node graph
    rows_u, rows_v = [], []
    for kind, payload, src, dst in edges:
        if kind == 'xshare':
            rows_u.append(nf + src); rows_v.append(dst)
        else:
            for cp in (0, 1):
                rows_u.append(cp * nf + src); rows_v.append(cp * nf + dst)
    # flat 0 of both copies (H = 0) in one class
    rows_u.append(np.array([0])); rows_v.append(np.array([nf]))
    U = np.concatenate(rows_u) if rows_u else np.zeros(0, dtype=np.int64)
    V = np.concatenate(rows_v) if rows_v else np.zeros(0, dtype=np.int64)
    G = sp.coo_matrix((np.ones(len(U)), (U, V)), shape=(2 * nf, 2 * nf))
    ncomp, lab = connected_components(G, directed=False)
    if verbose:
        print(f"  classes: {ncomp} (nodes {2 * nf}); edges merge {nmerge}, pmerge {npm}, xshare {nxs} "
              f"({time.time() - t0:.1f}s)", flush=True)
    return lab, edges


