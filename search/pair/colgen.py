"""Column generation on the certificate LP (lazy elemental Shannon rows over the full lattice) for two-set exponent
schemes with D and W vertices.  Columns are joint classes of nodes (copy, flat) under the configuration's
automorphisms (both copies), partial substitutions (pmerge, within a copy) and cross-copy partial identifications
(xshare); the corresponding certificate rows are written explicitly (tree flows), so the output is checked by
check3.py with no new row types.
Usage: python colgen.py '<job json>' OUTPREFIX [rounds]
job keys: as sweep2.build (nD, W, forms/ex, M, max_flats), pmerge (0/1/2), xshare (bool).
env: ADD (rows per round, default 300000), ADDFRAC (0.2), ADDMAX (2000000), VTOL (1e-7), STALL (2), AGE (0 = never
drop rows), INIT_FROM (active-row descriptors of an earlier run), WORKERS (oracle processes, default 32)."""
